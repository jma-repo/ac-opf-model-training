"""One per-unit case representation (MATPOWER conventions) built from the
pandapower net, plus writers for MATPOWER (.m), PowerModels JSON and the
GridSFM/OPFData .pyg.json. All three exports derive from the same arrays, so
they are numerically identical by construction.

MATPOWER conventions: bus/gen/branch in MW, MVAr and per-unit impedance on
baseMVA; gencost model 2 (polynomial) in $/MW^2h, $/MWh, $/h."""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

ANG_DEG = 30.0


def build_case(net, solved: bool = False) -> dict:
    base = float(net.sn_mva)
    w = 2 * math.pi * float(net.f_hz)
    buses = list(net.bus.index)
    num = {b: i + 1 for i, b in enumerate(buses)}       # MATPOWER bus numbers 1..N
    slack = set(net.gen.bus[net.gen.slack]) | set(net.ext_grid.bus)
    gen_buses = set(net.gen.bus)
    pd = net.load.groupby("bus").p_mw.sum()
    qd = net.load.groupby("bus").q_mvar.sum()
    rb = net.res_bus if solved else None

    bus = np.zeros((len(buses), 13))
    for i, b in enumerate(buses):
        r = net.bus.loc[b]
        bus[i] = [num[b], 3 if b in slack else 2 if b in gen_buses else 1,
                  pd.get(b, 0.0), qd.get(b, 0.0), 0, 0, 1,
                  rb.vm_pu[b] if solved else 1.0, rb.va_degree[b] if solved else 0.0,
                  r.vn_kv, 1, r.max_vm_pu, r.min_vm_pu]

    cost = net.poly_cost[net.poly_cost.et == "gen"].set_index("element")
    gen = np.zeros((len(net.gen), 21))
    gencost = np.zeros((len(net.gen), 7))
    for k, (g, r) in enumerate(net.gen.iterrows()):
        pg = net.res_gen.p_mw[g] if solved else r.p_mw
        qg = net.res_gen.q_mvar[g] if solved else 0.0
        gen[k, :10] = [num[r.bus], pg, qg, r.max_q_mvar, r.min_q_mvar, r.vm_pu,
                       max(r.max_p_mw, 1.0), 1, r.max_p_mw, r.min_p_mw]
        c = cost.loc[g] if g in cost.index else None
        gencost[k] = [2, 0, 0, 3, c.cp2_eur_per_mw2 if c is not None else 0,
                      c.cp1_eur_per_mw if c is not None else 0, c.cp0_eur if c is not None else 0]

    nl, nt = len(net.line), len(net.trafo)
    branch = np.zeros((nl + nt, 13))
    for k, (_, r) in enumerate(net.line.iterrows()):
        vn = net.bus.vn_kv[r.from_bus]
        zb = vn ** 2 / base
        rate = math.sqrt(3) * r.max_i_ka * vn
        branch[k] = [num[r.from_bus], num[r.to_bus], r.r_ohm_per_km * r.length_km / zb,
                     r.x_ohm_per_km * r.length_km / zb, w * r.c_nf_per_km * 1e-9 * r.length_km * zb,
                     rate, rate, rate, 0, 0, 1, -ANG_DEG, ANG_DEG]
    for k, (_, r) in enumerate(net.trafo.iterrows()):
        z = r.vk_percent / 100 * base / r.sn_mva
        R = r.vkr_percent / 100 * base / r.sn_mva
        branch[nl + k] = [num[r.hv_bus], num[r.lv_bus], R, math.sqrt(max(z * z - R * R, 1e-12)), 0,
                          r.sn_mva, r.sn_mva, r.sn_mva, 1.0, 0, 1, -ANG_DEG, ANG_DEG]
    case = {"version": "2", "baseMVA": base, "bus": bus, "gen": gen, "branch": branch,
            "gencost": gencost, "n_line": nl, "n_trafo": nt,
            "bus_names": net.bus.name.tolist(), "gen_names": net.gen.name.tolist(),
            "load_bus": [num[b] for b in net.load.bus], "load_pq": net.load[["p_mw", "q_mvar"]].values,
            "objective": float(net.res_cost) if solved else None}
    if solved:
        rl, rt = net.res_line, net.res_trafo
        case["flows"] = np.r_[np.c_[rl.p_from_mw, rl.q_from_mvar, rl.p_to_mw, rl.q_to_mvar],
                              np.c_[rt.p_hv_mw, rt.q_hv_mvar, rt.p_lv_mw, rt.q_lv_mvar]]
    return case


# ------------------------------------------------------------------ MATPOWER
def write_matpower(case: dict, path: Path, name="alberta_open_approx"):
    def block(a, fmt):
        return "\n".join("\t" + "\t".join(fmt.format(v) for v in row) + ";" for row in a)
    g = "{:.10g}"
    txt = [f"function mpc = {name}",
           "% Approximate open-data model of the Alberta HV grid. NOT AESO's grid model.",
           "% Generated by abgrid (see README for sources, licences and provenance).",
           "% Cost curves are illustrative only.",
           "mpc.version = '2';", f"mpc.baseMVA = {case['baseMVA']:g};",
           "%% bus_i type Pd Qd Gs Bs area Vm Va baseKV zone Vmax Vmin",
           "mpc.bus = [", block(case["bus"], g), "];",
           "%% bus Pg Qg Qmax Qmin Vg mBase status Pmax Pmin ...",
           "mpc.gen = [", block(case["gen"][:, :10], g), "];",
           "%% fbus tbus r x b rateA rateB rateC ratio angle status angmin angmax",
           "mpc.branch = [", block(case["branch"], g), "];",
           "%% 2 startup shutdown n c2 c1 c0",
           "mpc.gencost = [", block(case["gencost"], g), "];",
           "mpc.bus_name = {", *[f"\t'{n}';" for n in case["bus_names"]], "};"]
    Path(path).write_text("\n".join(txt) + "\n")


# ------------------------------------------------------------------ PowerModels
def to_powermodels(case: dict) -> dict:
    """PowerModels network data dictionary (per-unit, radians)."""
    base = case["baseMVA"]
    rad = math.radians
    pm = {"name": "alberta_open_approx", "baseMVA": base, "per_unit": True,
          "source_type": "abgrid", "source_version": "0.1",
          "bus": {}, "gen": {}, "branch": {}, "load": {}, "shunt": {}, "dcline": {},
          "storage": {}, "switch": {}}
    for r in case["bus"]:
        i = int(r[0])
        pm["bus"][str(i)] = {"index": i, "bus_i": i, "bus_type": int(r[1]), "vm": r[7], "va": rad(r[8]),
                             "base_kv": r[9], "zone": 1, "area": 1, "vmax": r[11], "vmin": r[12],
                             "name": case["bus_names"][i - 1]}
    for k, (r, c) in enumerate(zip(case["gen"], case["gencost"]), 1):
        pm["gen"][str(k)] = {"index": k, "gen_bus": int(r[0]), "pg": r[1] / base, "qg": r[2] / base,
                             "qmax": r[3] / base, "qmin": r[4] / base, "vg": r[5], "mbase": r[6],
                             "gen_status": 1, "pmax": r[8] / base, "pmin": r[9] / base,
                             "model": 2, "ncost": 3, "startup": 0.0, "shutdown": 0.0,
                             "cost": [c[4] * base ** 2, c[5] * base, c[6]],
                             "name": case["gen_names"][k - 1]}
    nl = case["n_line"]
    for k, r in enumerate(case["branch"], 1):
        pm["branch"][str(k)] = {"index": k, "f_bus": int(r[0]), "t_bus": int(r[1]), "br_r": r[2],
                                "br_x": r[3], "b_fr": r[4] / 2, "b_to": r[4] / 2, "g_fr": 0.0, "g_to": 0.0,
                                "rate_a": r[5] / base, "rate_b": r[6] / base, "rate_c": r[7] / base,
                                "tap": r[8] if r[8] else 1.0, "shift": 0.0, "br_status": 1,
                                "angmin": rad(r[11]), "angmax": rad(r[12]), "transformer": k > nl}
    for k, (b, (p, q)) in enumerate(zip(case["load_bus"], case["load_pq"]), 1):
        pm["load"][str(k)] = {"index": k, "load_bus": int(b), "pd": p / base, "qd": q / base, "status": 1}
    return pm


# ------------------------------------------------------------------ GridSFM / OPFData
def to_gridsfm(case: dict, meta: dict | None = None) -> dict:
    base = case["baseMVA"]
    rad = math.radians(ANG_DEG)
    bus = [[r[9], int(r[1]), r[12], r[11]] for r in case["bus"]]
    gens = [[r[6], r[1] / base, r[9] / base, r[8] / base, r[2] / base, r[4] / base, r[3] / base, r[5],
             c[4] * base ** 2, c[5] * base, c[6]] for r, c in zip(case["gen"], case["gencost"])]
    loads = [[p / base, q / base] for p, q in case["load_pq"]]
    nl = case["n_line"]
    L, T = case["branch"][:nl], case["branch"][nl:]
    lf = [[-rad, rad, r[4] / 2, r[4] / 2, r[2], r[3], r[5] / base, r[6] / base, r[7] / base] for r in L]
    tf = [[-rad, rad, r[2], r[3], r[5] / base, r[6] / base, r[7] / base, r[8] or 1.0, 0.0, 0.0, 0.0] for r in T]
    edge = lambda a: ([int(x) - 1 for x in a[:, 0]], [int(x) - 1 for x in a[:, 1]])  # noqa: E731
    ls, lr = edge(L)
    ts, tr = edge(T)
    out = {"grid": {
        "nodes": {"bus": bus, "generator": gens, "load": loads, "shunt": []},
        "edges": {"ac_line": {"senders": ls, "receivers": lr, "features": lf},
                  "transformer": {"senders": ts, "receivers": tr, "features": tf},
                  "generator_link": {"senders": list(range(len(gens))),
                                     "receivers": [int(r[0]) - 1 for r in case["gen"]]},
                  "load_link": {"senders": list(range(len(loads))),
                                "receivers": [int(b) - 1 for b in case["load_bus"]]},
                  "shunt_link": {"senders": [], "receivers": []}},
        "context": [[[base]]]}}
    if case.get("flows") is not None:
        f = case["flows"] / base
        out["solution"] = {
            "nodes": {"bus": [[math.radians(r[8]), r[7]] for r in case["bus"]],
                      "generator": [[r[1] / base, r[2] / base] for r in case["gen"]]},
            "edges": {"ac_line": {"senders": ls, "receivers": lr, "features": f[:nl].tolist()},
                      "transformer": {"senders": ts, "receivers": tr, "features": f[nl:].tolist()}}}
    out["metadata"] = {"objective": case["objective"], "feasible": case["objective"] is not None,
                       "bus_names": case["bus_names"], "gen_names": case["gen_names"],
                       "disclaimer": "Approximate open-data Alberta model; NOT AESO's grid.", **(meta or {})}
    return out


def _json_default(o):
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    if isinstance(o, np.ndarray):
        return o.tolist()
    raise TypeError(type(o))


def write_all(net, out_dir: Path, stem: str, solved: bool, meta=None) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    case = build_case(net, solved=solved)
    write_matpower(case, out_dir / f"{stem}.m")
    (out_dir / f"{stem}.powermodels.json").write_text(json.dumps(to_powermodels(case), default=_json_default))
    (out_dir / f"{stem}.pyg.json").write_text(json.dumps(to_gridsfm(case, meta), default=_json_default))
    return case
